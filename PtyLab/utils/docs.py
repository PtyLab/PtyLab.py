"""Run the tutorial scripts in docs/tutorials/scripts/ and write them as pages in docs/tutorials/.

Each tutorial is a percent-format script (`# %%` code cells, `# %% [markdown]`
text cells). It is executed cell by cell in a Jupyter kernel, and the result is
written to docs/tutorials/ as `<name>.md`, with its figures in `<name>_files/`.
The first line of each page records a hash of the script, so a page that is out
of date is found without running anything.

The page offers the tutorial for download as a script and as a `<name>.ipynb`
notebook without outputs. The notebooks are not committed: they are converted
from the scripts, without running them, before each documentation build.

    uv run ptylab docs render                # tutorials whose script changed
    uv run ptylab docs render tutorial_CPM   # one, always
    uv run ptylab docs render --all          # all
    uv run ptylab docs notebooks             # the download notebooks, before a build
    uv run ptylab docs check                 # CI

Only works in a git checkout of PtyLab.py, which has the docs/ folder.
"""

import base64
import hashlib
import posixpath
import re
import shutil
import tempfile
from pathlib import Path

import jupytext
import nbformat
from nbclient import NotebookClient

REPO = Path(__file__).resolve().parents[2]
PAGES = (
    REPO / "docs" / "tutorials"
)  # pages, figures and notebooks generated from the scripts, plus index.md
SOURCES = PAGES / "scripts"  # the scripts, written by hand
SITE = "https://ptylab.github.io/PtyLab.py/"
HEADER = "<!-- source-sha256: {} (generated by `ptylab docs render` from scripts/{}, do not edit) -->"
# Download buttons for the notebook, served next to the page, and the script in scripts/
# (`.md-button` is the theme's button style; needs the attr_list extension).
BUTTONS = (
    '[Download Jupyter notebook]({stem}.ipynb){{ .md-button download="{stem}.ipynb" }} '
    '[Download Python source](scripts/{stem}.py){{ .md-button download="{stem}.py" }}\n'
)
# shown below the introduction, and the buttons again at the end of the page
DOWNLOAD_TOP = (
    '!!! tip "Run it yourself"\n'
    "    Run this tutorial as a Jupyter notebook, or as a Python script with `python {stem}.py`.\n\n    "
    + BUTTONS
)
DOWNLOAD_END = "---\n\n" + BUTTONS
ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")
MD_LINK = re.compile(r"\]\(((?:\.\./)?[\w/-]+)\.md\)")


def scripts() -> list[Path]:
    if not SOURCES.is_dir() or not PAGES.is_dir():
        raise SystemExit(
            "ptylab docs only works in a git checkout of PtyLab.py (docs/tutorials/scripts/ not found)."
        )
    return sorted(SOURCES.glob("tutorial_*.py"))


def source_hash(script: Path) -> str:
    # Hash with "\n" line endings, so a Windows checkout (CRLF) gives the same hash.
    text = script.read_text(encoding="utf-8").replace("\r\n", "\n")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def header(script: Path) -> str:
    return HEADER.format(source_hash(script), script.name)


def notebook_text(script: Path) -> str:
    """The downloadable notebook: the script's cells, no outputs."""
    notebook = jupytext.read(script)
    notebook.metadata = {
        "kernelspec": {
            "display_name": "Python 3",
            "language": "python",
            "name": "python3",
        },
        "language_info": {"name": "python"},
    }
    for i, cell in enumerate(notebook.cells):
        # fixed ids: nbformat would pick random ones, and the check compares the file in full
        cell.id = f"cell-{i}"
        cell.metadata = {}
        if cell.cell_type == "markdown":
            # links to other docs pages point to the website, since the .md files are not downloaded
            cell.source = MD_LINK.sub(
                lambda m: f"]({SITE}{posixpath.normpath('tutorials/' + m.group(1))}/)",
                cell.source,
            )
    return nbformat.writes(notebook) + "\n"


def clean_text(text: str) -> str:
    # Progress bars (tqdm) redraw a line with "\r"; keep only the last state of each line.
    text = ANSI.sub("", text)
    return "\n".join(line.rsplit("\r", 1)[-1] for line in text.splitlines())


def text_block(text: str) -> str:
    text = clean_text(text).strip("\n")
    return f"```text\n{text}\n```\n" if text.strip() else ""


class PageClient(NotebookClient):
    """Executes a notebook so that each cell keeps the figures it drew.

    The PtyLab Monitor reuses one figure across engines and updates it through a
    display id. In Jupyter that rewrites the output of the cell that first showed
    it; on a static page the later cell would then show nothing. Here an update
    that only targets earlier cells becomes a new output of the running cell, and
    the earlier cell keeps the figure as it was when that cell finished.
    """

    def process_message(self, msg, cell, cell_index):
        content = msg["content"]
        display_id = (content.get("transient") or {}).get("display_id")
        if msg[
            "msg_type"
        ] == "update_display_data" and cell_index not in self._display_id_map.get(
            display_id, {}
        ):
            self._display_id_map.pop(display_id, None)
            msg["msg_type"] = msg["header"]["msg_type"] = "display_data"
        return super().process_message(msg, cell, cell_index)


def render_outputs(outputs, stem: str, files_dir: Path, cell_index: int) -> list[str]:
    # All text a cell printed (prints, logging, progress bars) goes in one block
    # first, so a progress bar split over many chunks collapses to its last state.
    stream = "".join(out.text for out in outputs if out.output_type == "stream")
    parts = [text_block(stream)]
    for j, out in enumerate(outputs):
        if out.output_type == "stream":
            continue
        if out.output_type == "error":
            parts.append(text_block("\n".join(out.traceback)))
            continue
        data = out.get("data", {})
        if "application/vnd.jupyter.widget-view+json" in data:
            # Widgets (tqdm progress bars) only live in a running kernel; their text
            # fallback is the initial "0%" state, so leave them out.
            continue
        if "image/png" in data:
            name = f"cell{cell_index:02d}_{j}.png"
            files_dir.mkdir(exist_ok=True)
            (files_dir / name).write_bytes(base64.b64decode(data["image/png"]))
            parts.append(f"![]({stem}_files/{name})\n")
        elif "text/html" in data:
            parts.append(data["text/html"] + "\n")
        elif "text/plain" in data:
            parts.append(text_block(data["text/plain"]))
    return [p for p in parts if p]


def render(script: Path, timeout: int = 3600) -> None:
    stem = script.stem
    notebook = jupytext.read(script)
    with tempfile.TemporaryDirectory() as workdir:
        # Run in a scratch directory so results saved by the tutorial stay out of the repo.
        PageClient(
            notebook,
            timeout=timeout,
            kernel_name="python3",
            resources={"metadata": {"path": workdir}},
        ).execute()

    files_dir = PAGES / f"{stem}_files"
    shutil.rmtree(files_dir, ignore_errors=True)
    parts = [header(script) + "\n"]
    for i, cell in enumerate(notebook.cells):
        if cell.cell_type == "markdown":
            parts.append(cell.source + "\n")
            if i == 0:
                parts.append(DOWNLOAD_TOP.format(stem=stem))
        elif cell.cell_type == "code" and cell.source.strip():
            parts.append(f"```python\n{cell.source}\n```\n")
            parts.extend(render_outputs(cell.outputs, stem, files_dir, i))
    parts.append(DOWNLOAD_END.format(stem=stem))
    (PAGES / f"{stem}.md").write_text("\n".join(parts), encoding="utf-8")
    write_notebook(script)


def write_notebook(script: Path) -> None:
    (PAGES / f"{script.stem}.ipynb").write_text(notebook_text(script), encoding="utf-8")


def read(path: Path) -> str | None:
    return (
        path.read_text(encoding="utf-8").replace("\r\n", "\n")
        if path.exists()
        else None
    )


def is_current(script: Path) -> bool:
    page = read(PAGES / f"{script.stem}.md")
    return page is not None and page.split("\n", 1)[0] == header(script)


def problems() -> list[str]:
    """Everything that is not in sync between the scripts, their pages and the nav."""
    found = []
    nav = (REPO / "mkdocs.yml").read_text(encoding="utf-8")
    index = (PAGES / "index.md").read_text(encoding="utf-8")
    for script in scripts():
        stem = script.stem
        if not is_current(script):
            found.append(
                f"out of date: docs/tutorials/{stem}.md (run `uv run ptylab docs render {stem}`)"
            )
        if f"tutorials/{stem}.md" not in nav:
            found.append(
                f"not in the mkdocs.yml nav: add tutorials/{stem}.md under Tutorials"
            )
        if f"({stem}.md)" not in index:
            found.append(
                f"not listed in docs/tutorials/index.md: add a line linking {stem}.md"
            )
    sources = {s.stem for s in scripts()}
    for page in sorted(PAGES.glob("tutorial_*.md")):
        if page.stem not in sources:
            found.append(
                f"no script for docs/tutorials/{page.name}: delete its .md and _files/"
            )
    return found


def render_command(names: list[str], all_: bool, timeout: int) -> int:
    if names:
        # a named tutorial is always rendered, even if it is current
        selected = [SOURCES / f"{Path(name).stem}.py" for name in names]
        missing = [s.name for s in selected if not s.exists()]
        if missing:
            raise SystemExit(
                f"not found in docs/tutorials/scripts/: {', '.join(missing)}"
            )
    else:
        selected = [s for s in scripts() if all_ or not is_current(s)]
        if not selected:
            print(
                "All tutorial pages are up to date (use --all to render them anyway)."
            )
    for script in selected:
        print(f"rendering scripts/{script.name} ...", flush=True)
        render(script, timeout)
    for problem in problems():
        print(problem)
    return 0


def notebooks_command() -> int:
    for script in scripts():
        write_notebook(script)
    print(f"Wrote {len(scripts())} notebooks to docs/tutorials/.")
    return 0


def check_command() -> int:
    found = problems()
    for problem in found:
        print(problem)
    if not found:
        print("All tutorial pages are up to date.")
    return 1 if found else 0
