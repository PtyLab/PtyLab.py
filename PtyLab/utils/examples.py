"""Build the example pages in docs/examples/ from the scripts in docs/examples/scripts/.

Each example is a percent-format script (`# %%` code cells, `# %% [markdown]`
text cells). Only the scripts and the outputs of their code cells are committed:

    docs/examples/scripts/<name>.py          the script, written by hand
    docs/examples/outputs/<name>/            outputs.json (code hash + output of each
                                             code cell) and the figures, from `render`
    docs/examples/<name>.md, <name>.ipynb    the page and download notebook, from
                                             `build` (git-ignored)

`render` executes a script in a Jupyter kernel and stores its outputs. `build`
joins the current text of each script with the stored outputs, without running
anything, so a text-only change needs no render. The outputs are valid as long
as the code cells are unchanged, which the code hash in outputs.json records.

    uv run ptylab examples render                # run examples whose code changed, then write all pages
    uv run ptylab examples render example_CPM    # one, always run
    uv run ptylab examples render --all          # all
    uv run ptylab examples build                 # write all pages, never runs anything (CI)
    uv run ptylab examples check                 # CI

Only works in a git checkout of PtyLab.py, which has the docs/ folder.
"""

import base64
import hashlib
import json
import os
import posixpath
import re
import shutil
import tempfile
from pathlib import Path

import jupytext
import nbformat
from jupyter_client.manager import KernelManager
from nbclient import NotebookClient

REPO = Path(__file__).resolve().parents[2]
PAGES = REPO / "docs" / "examples"  # generated pages and notebooks, plus index.md
SOURCES = PAGES / "scripts"  # the scripts, written by hand
OUTPUTS = PAGES / "outputs"  # committed outputs of each script, one folder per example
SITE = "https://ptylab.github.io/PtyLab.py/"
HEADER = "<!-- generated by `ptylab examples` from scripts/{}, do not edit -->"
# Download buttons for the notebook, served next to the page, and the script in scripts/
# (`.md-button` is the theme's button style; needs the attr_list extension).
BUTTONS = (
    '[Download Jupyter notebook]({stem}.ipynb){{ .md-button download="{stem}.ipynb" }} '
    '[Download Python source](scripts/{stem}.py){{ .md-button download="{stem}.py" }}\n'
)
# shown below the introduction, and the buttons again at the end of the page
DOWNLOAD_TOP = (
    '!!! tip "Run it yourself"\n'
    "    Run this example as a Jupyter notebook, or as a Python script.\n\n    "
    + BUTTONS
)
DOWNLOAD_END = "---\n\n" + BUTTONS
ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")
# Warnings name the cell as a temporary file (/tmp/ipykernel_<pid>/<hash>.py) that
# changes on every run; replaced, so a rerun does not change outputs.json for nothing.
CELL_FILE = re.compile(r"\S*ipykernel_\d+[/\\]\d+\.py")
# The monitor advises an interactive backend for verboseLevel="high", which a static
# page cannot use; hidden while rendering. Notebook readers still see it.
HIDDEN_WARNINGS = "ignore:For diffraction data plot:UserWarning"
MD_LINK = re.compile(r"\]\(((?:\.\./)?[\w/-]+)\.md\)")


def scripts() -> list[Path]:
    if not SOURCES.is_dir():
        raise SystemExit(
            "ptylab examples only works in a git checkout of PtyLab.py (docs/examples/scripts/ not found)."
        )
    return sorted(SOURCES.glob("example_*.py"))


def shown(cell) -> bool:
    """A code cell that appears on the page (empty ones are skipped)."""
    return cell.cell_type == "code" and bool(cell.source.strip())


def code_hash(notebook) -> str:
    """Hash of the code cells only, so text edits keep the stored outputs valid."""
    code = "\n# %%\n".join(c.source for c in notebook.cells if shown(c))
    return hashlib.sha256(code.encode("utf-8")).hexdigest()


def stored_outputs(script: Path, notebook) -> list[str] | None:
    """The stored output of each shown code cell, or None if missing or for older code."""
    path = OUTPUTS / script.stem / "outputs.json"
    if not path.exists():
        return None
    stored = json.loads(path.read_text(encoding="utf-8"))
    return stored["cells"] if stored["code"] == code_hash(notebook) else None


def notebook_text(script: Path) -> str:
    """The downloadable notebook: the script's cells, no outputs."""
    notebook = jupytext.read(script)
    notebook.metadata = {
        "kernelspec": {
            "display_name": "Python 3",
            "language": "python",
            "name": "python3",
        },
        "language_info": {"name": "python"},
    }
    for i, cell in enumerate(notebook.cells):
        # fixed ids: nbformat would pick random ones on every build
        cell.id = f"cell-{i}"
        cell.metadata = {}
        if cell.cell_type == "markdown":
            # links to other docs pages point to the website, since the .md files are not downloaded
            cell.source = MD_LINK.sub(
                lambda m: f"]({SITE}{posixpath.normpath('examples/' + m.group(1))}/)",
                cell.source,
            )
    return nbformat.writes(notebook) + "\n"


def clean_text(text: str) -> str:
    # Progress bars (tqdm) redraw a line with "\r"; keep only the last state of each line.
    text = CELL_FILE.sub("<cell>", ANSI.sub("", text))
    return "\n".join(line.rsplit("\r", 1)[-1] for line in text.splitlines())


def text_block(text: str) -> str:
    text = clean_text(text).strip("\n")
    return f"```text\n{text}\n```\n" if text.strip() else ""


class PageClient(NotebookClient):
    """Executes a notebook so that each cell keeps the figures it drew.

    The PtyLab Monitor reuses one figure across engines and updates it through a
    display id. In Jupyter that rewrites the output of the cell that first showed
    it; on a static page the later cell would then show nothing. Here an update
    that only targets earlier cells becomes a new output of the running cell, and
    the earlier cell keeps the figure as it was when that cell finished.
    """

    def process_message(self, msg, cell, cell_index):
        content = msg["content"]
        display_id = (content.get("transient") or {}).get("display_id")
        if msg[
            "msg_type"
        ] == "update_display_data" and cell_index not in self._display_id_map.get(
            display_id, {}
        ):
            self._display_id_map.pop(display_id, None)
            msg["msg_type"] = msg["header"]["msg_type"] = "display_data"
        return super().process_message(msg, cell, cell_index)


def render_outputs(outputs, stem: str, files_dir: Path, cell_index: int) -> list[str]:
    # All text a cell printed (prints, logging, progress bars) goes in one block
    # first, so a progress bar split over many chunks collapses to its last state.
    stream = "".join(out.text for out in outputs if out.output_type == "stream")
    parts = [text_block(stream)]
    for j, out in enumerate(outputs):
        if out.output_type == "stream":
            continue
        if out.output_type == "error":
            parts.append(text_block("\n".join(out.traceback)))
            continue
        data = out.get("data", {})
        if "application/vnd.jupyter.widget-view+json" in data:
            # Widgets (tqdm progress bars) only live in a running kernel; their text
            # fallback is the initial "0%" state, so leave them out.
            continue
        if "image/png" in data:
            name = f"cell{cell_index:02d}_{j}.png"
            files_dir.mkdir(parents=True, exist_ok=True)
            (files_dir / name).write_bytes(base64.b64decode(data["image/png"]))
            # relative to the page in docs/examples/
            parts.append(f"![](outputs/{stem}/{name})\n")
        elif "text/html" in data:
            parts.append(data["text/html"] + "\n")
        elif "text/plain" in data:
            parts.append(text_block(data["text/plain"]))
    return [p for p in parts if p]


def execute(notebook, stem: str, timeout: int) -> list[str]:
    """Run the notebook; return the rendered outputs of each code cell and rewrite the figures."""
    with tempfile.TemporaryDirectory() as workdir:
        # The kernel talks through socket files in the scratch directory rather than a
        # local TCP port, which ipykernel warns about (unencrypted). Windows has no
        # socket transport, so it keeps TCP and the warning.
        socket = (
            {} if os.name == "nt" else {"transport": "ipc", "ip": f"{workdir}/kernel"}
        )
        km = KernelManager(kernel_name="python3", **socket)
        filters = ",".join(
            filter(None, [os.environ.get("PYTHONWARNINGS"), HIDDEN_WARNINGS])
        )
        try:
            # Run in a scratch directory so results saved by the example stay out of the repo.
            PageClient(
                notebook,
                km=km,
                timeout=timeout,
                resources={"metadata": {"path": workdir}},
            ).execute(env={**os.environ, "PYTHONWARNINGS": filters})
        finally:
            # a kernel manager we pass in is not shut down by nbclient
            if km.has_kernel:
                km.shutdown_kernel(now=True)
    files_dir = OUTPUTS / stem
    shutil.rmtree(files_dir, ignore_errors=True)
    # Figures are named by the cell's index among all cells, so they are found by cell.
    return [
        "\n".join(render_outputs(cell.outputs, stem, files_dir, i))
        for i, cell in enumerate(notebook.cells)
        if shown(cell)
    ]


def render(script: Path, timeout: int = 3600) -> None:
    """Run the script and store the outputs of its code cells."""
    notebook = jupytext.read(script)
    cells = execute(notebook, script.stem, timeout)
    path = OUTPUTS / script.stem / "outputs.json"
    path.parent.mkdir(parents=True, exist_ok=True)
    stored = {"code": code_hash(notebook), "cells": cells}
    path.write_text(json.dumps(stored, indent=1) + "\n", encoding="utf-8")


def page_text(script: Path, notebook, outputs: list[str]) -> str:
    """The page: the script's text and code, each code cell followed by its output."""
    stem = script.stem
    remaining = iter(outputs)
    parts = [HEADER.format(script.name) + "\n"]
    for i, cell in enumerate(notebook.cells):
        if cell.cell_type == "markdown":
            parts.append(cell.source + "\n")
            if i == 0:
                parts.append(DOWNLOAD_TOP.format(stem=stem))
        elif shown(cell):
            parts.append(f"```python\n{cell.source}\n```\n")
            output = next(remaining)
            if output:
                parts.append(output + "\n")
    parts.append(DOWNLOAD_END.format(stem=stem))
    return "\n".join(parts)


def build(script: Path) -> bool:
    """Write the page and notebook from the stored outputs; False if they are out of date."""
    notebook = jupytext.read(script)
    outputs = stored_outputs(script, notebook)
    if outputs is None:
        return False
    page = page_text(script, notebook, outputs)
    (PAGES / f"{script.stem}.md").write_text(page, encoding="utf-8")
    (PAGES / f"{script.stem}.ipynb").write_text(notebook_text(script), encoding="utf-8")
    return True


def is_current(script: Path) -> bool:
    return stored_outputs(script, jupytext.read(script)) is not None


def problems() -> list[str]:
    """Everything that is not in sync between the scripts, their outputs and the nav."""
    found = []
    nav = (REPO / "mkdocs.yml").read_text(encoding="utf-8")
    index = (PAGES / "index.md").read_text(encoding="utf-8")
    for script in scripts():
        stem = script.stem
        if not is_current(script):
            found.append(
                f"no outputs for the current code of {stem} (run `uv run ptylab examples render {stem}`)"
            )
        if f"examples/{stem}.md" not in nav:
            found.append(
                f"not in the mkdocs.yml nav: add examples/{stem}.md under Examples"
            )
        if f"({stem}.md)" not in index:
            found.append(
                f"not listed in docs/examples/index.md: add a line linking {stem}.md"
            )
    sources = {s.stem for s in scripts()}
    if OUTPUTS.is_dir():
        for folder in sorted(p for p in OUTPUTS.iterdir() if p.is_dir()):
            if folder.name not in sources:
                found.append(
                    f"no script for docs/examples/outputs/{folder.name}/: delete it"
                )
    return found


def build_command() -> int:
    # Generated files of removed or renamed examples would otherwise linger.
    for path in [*PAGES.glob("example_*.md"), *PAGES.glob("example_*.ipynb")]:
        path.unlink()
    built = [s for s in scripts() if build(s)]
    print(f"Wrote {len(built)} example pages and notebooks to docs/examples/.")
    return check_command() if len(built) < len(scripts()) else 0


def confirm(question: str) -> bool:
    """Ask a yes/no question; only "y" or "yes" counts as yes (Enter, or no terminal, is no)."""
    try:
        return input(question).strip().lower() in ("y", "yes")
    except EOFError:
        return False


def render_command(names: list[str], all_: bool, timeout: int) -> int:
    if names:
        # a named example is always run, even if its outputs are current
        selected = [SOURCES / f"{Path(name).stem}.py" for name in names]
        missing = [s.name for s in selected if not s.exists()]
        if missing:
            raise SystemExit(
                f"not found in docs/examples/scripts/: {', '.join(missing)}"
            )
    else:
        if all_ and not confirm(
            "This runs all examples, which can take half an hour or more. Continue? [y/N] "
        ):
            print("Cancelled.")
            return 1
        selected = [s for s in scripts() if all_ or not is_current(s)]
        if not selected:
            print("All example outputs are up to date (use --all to run them anyway).")
    for script in selected:
        print(f"running scripts/{script.name} ...", flush=True)
        render(script, timeout)
    return build_command()


def check_command() -> int:
    found = problems()
    for problem in found:
        print(problem)
    if not found:
        print("All example outputs are up to date.")
    return 1 if found else 0
