"""Run the tutorial scripts in docs/tutorials/ and write them as Markdown pages.

Each tutorial is a percent-format script (`# %%` code cells, `# %% [markdown]`
text cells). It is executed cell by cell in a Jupyter kernel, and the result is
written next to it as `<name>.md`, with its figures in `<name>_files/`. A
`<name>.ipynb` copy without outputs is written as well, for download from the page.
The first line of each page records a hash of the script, so `--check` can tell
whether a page or notebook is out of date without running anything.

    uv run --group docs python docs/render_tutorials.py              # all
    uv run --group docs python docs/render_tutorials.py tutorial_CPM # one
    uv run --group docs python docs/render_tutorials.py --check      # CI
"""

import argparse
import base64
import hashlib
import posixpath
import re
import shutil
import sys
import tempfile
from pathlib import Path

import jupytext
import nbformat
from nbclient import NotebookClient

TUTORIALS = Path(__file__).resolve().parent / "tutorials"
SITE = "https://ptylab.github.io/PtyLab.py/"
HEADER = "<!-- source-sha256: {} (generated by docs/render_tutorials.py, do not edit) -->"
# Download buttons for the script and notebook, which are served next to the page
# (`.md-button` is the theme's button style; needs the attr_list extension).
BUTTONS = (
    '[Download Jupyter notebook]({stem}.ipynb){{ .md-button download="{stem}.ipynb" }} '
    '[Download Python source]({stem}.py){{ .md-button download="{stem}.py" }}\n'
)
# shown below the introduction, and the buttons again at the end of the page
DOWNLOAD_TOP = (
    '!!! tip "Run it yourself"\n'
    "    Run this tutorial as a Jupyter notebook, or as a Python script with `python {stem}.py`.\n\n    "
    + BUTTONS
)
DOWNLOAD_END = "---\n\n" + BUTTONS
ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")
MD_LINK = re.compile(r"\]\(((?:\.\./)?[\w/-]+)\.md\)")


def source_hash(script: Path) -> str:
    # Hash with "\n" line endings, so a Windows checkout (CRLF) gives the same hash.
    text = script.read_text(encoding="utf-8").replace("\r\n", "\n")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def notebook_text(script: Path) -> str:
    """The downloadable notebook: the script's cells, no outputs."""
    notebook = jupytext.read(script)
    notebook.metadata = {
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python"},
    }
    for i, cell in enumerate(notebook.cells):
        # fixed ids: nbformat would pick random ones, and --check compares the file in full
        cell.id = f"cell-{i}"
        cell.metadata = {}
        if cell.cell_type == "markdown":
            # links to other docs pages point to the website, since the .md files are not downloaded
            cell.source = MD_LINK.sub(lambda m: f"]({SITE}{posixpath.normpath('tutorials/' + m.group(1))}/)", cell.source)
    return nbformat.writes(notebook) + "\n"


def clean_text(text: str) -> str:
    # Progress bars (tqdm) redraw a line with "\r"; keep only the last state of each line.
    text = ANSI.sub("", text)
    return "\n".join(line.rsplit("\r", 1)[-1] for line in text.splitlines())


def text_block(text: str) -> str:
    text = clean_text(text).strip("\n")
    return f"```text\n{text}\n```\n" if text.strip() else ""


class PageClient(NotebookClient):
    """Executes a notebook so that each cell keeps the figures it drew.

    The PtyLab Monitor reuses one figure across engines and updates it through a
    display id. In Jupyter that rewrites the output of the cell that first showed
    it; on a static page the later cell would then show nothing. Here an update
    that only targets earlier cells becomes a new output of the running cell, and
    the earlier cell keeps the figure as it was when that cell finished.
    """

    def process_message(self, msg, cell, cell_index):
        content = msg["content"]
        display_id = (content.get("transient") or {}).get("display_id")
        if msg["msg_type"] == "update_display_data" and cell_index not in self._display_id_map.get(display_id, {}):
            self._display_id_map.pop(display_id, None)
            msg["msg_type"] = msg["header"]["msg_type"] = "display_data"
        return super().process_message(msg, cell, cell_index)


def render_outputs(outputs, stem: str, files_dir: Path, cell_index: int) -> list[str]:
    # All text a cell printed (prints, logging, progress bars) goes in one block
    # first, so a progress bar split over many chunks collapses to its last state.
    stream = "".join(out.text for out in outputs if out.output_type == "stream")
    parts = [text_block(stream)]
    for j, out in enumerate(outputs):
        if out.output_type == "stream":
            continue
        if out.output_type == "error":
            parts.append(text_block("\n".join(out.traceback)))
            continue
        data = out.get("data", {})
        if "application/vnd.jupyter.widget-view+json" in data:
            # Widgets (tqdm progress bars) only live in a running kernel; their text
            # fallback is the initial "0%" state, so leave them out.
            continue
        if "image/png" in data:
            name = f"cell{cell_index:02d}_{j}.png"
            files_dir.mkdir(exist_ok=True)
            (files_dir / name).write_bytes(base64.b64decode(data["image/png"]))
            parts.append(f"![]({stem}_files/{name})\n")
        elif "text/html" in data:
            parts.append(data["text/html"] + "\n")
        elif "text/plain" in data:
            parts.append(text_block(data["text/plain"]))
    return [p for p in parts if p]


def render(script: Path, timeout: int) -> None:
    stem = script.stem
    notebook = jupytext.read(script)
    with tempfile.TemporaryDirectory() as workdir:
        # Run in a scratch directory so results saved by the tutorial stay out of the repo.
        PageClient(
            notebook,
            timeout=timeout,
            kernel_name="python3",
            resources={"metadata": {"path": workdir}},
        ).execute()

    files_dir = TUTORIALS / f"{stem}_files"
    shutil.rmtree(files_dir, ignore_errors=True)
    parts = [HEADER.format(source_hash(script)) + "\n"]
    for i, cell in enumerate(notebook.cells):
        if cell.cell_type == "markdown":
            parts.append(cell.source + "\n")
            if i == 0:
                parts.append(DOWNLOAD_TOP.format(stem=stem))
        elif cell.cell_type == "code" and cell.source.strip():
            parts.append(f"```python\n{cell.source}\n```\n")
            parts.extend(render_outputs(cell.outputs, stem, files_dir, i))
    parts.append(DOWNLOAD_END.format(stem=stem))
    (TUTORIALS / f"{stem}.md").write_text("\n".join(parts), encoding="utf-8")
    script.with_suffix(".ipynb").write_text(notebook_text(script), encoding="utf-8")


def is_current(script: Path) -> bool:
    page, notebook = script.with_suffix(".md"), script.with_suffix(".ipynb")
    if not page.exists() or not notebook.exists():
        return False
    first_line = page.read_text(encoding="utf-8").split("\n", 1)[0]
    # the notebook is cheap to rebuild, so compare it in full
    same_notebook = notebook.read_text(encoding="utf-8").replace("\r\n", "\n") == notebook_text(script)
    return first_line == HEADER.format(source_hash(script)) and same_notebook


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("names", nargs="*", help="tutorial names (default: all)")
    parser.add_argument("--check", action="store_true", help="only check that every page matches its script")
    parser.add_argument("--timeout", type=int, default=3600, help="seconds allowed per cell")
    args = parser.parse_args()

    scripts = sorted(TUTORIALS.glob("tutorial_*.py"))
    if args.names:
        scripts = [TUTORIALS / f"{Path(name).stem}.py" for name in args.names]

    if args.check:
        stale = [s.name for s in scripts if not is_current(s)]
        for name in stale:
            print(f"out of date: docs/tutorials/{name} (run docs/render_tutorials.py {Path(name).stem})")
        return 1 if stale else 0

    for script in scripts:
        print(f"rendering {script.name} ...", flush=True)
        render(script, args.timeout)
    return 0


if __name__ == "__main__":
    sys.exit(main())
